def register_guide(register):
    name = register["name"]
    if register["address"] in (0, 1, 2):
        return CONTROL_GUIDES[{0: "보드 상태", 1: "정류기 전원", 2: "운전 모드"}[register["address"]]]
    descriptions = {
        "set_voltage": "원하는 출력전압입니다. 현재 값을 더블클릭해 입력하세요. 전원이 ON일 때 출력전압이 설정값을 따라 서서히 변합니다. 모델의 최대 출력전압 범위 안에서 동작합니다.",
        "input_voltage": "정류기에 공급되는 입력전압입니다. 시험용 값을 입력할 수 있으며, 서버를 다시 시작하면 설정 파일의 입력전압으로 돌아갑니다.",
        "output_voltage": "현재 출력전압입니다. 전원과 설정전압에 따라 자동 계산됩니다. 그래프에서 전압이 목표에 도달하는 과정을 확인하세요.",
        "output_current": "현재 출력전류입니다. 환경 모델이 출력전압에 따라 계산합니다. 환경 모델이 꺼져 있으면 자동 갱신되지 않습니다.",
    }
    description = descriptions.get(name)
    if name.endswith("measured_potential"):
        description = "이 TB 지점의 측정전위입니다. 단위는 mV이며 음수로 표시됩니다. 환경 모델이 출력 상태에 따라 계산합니다. 환경 모델이 꺼져 있으면 자동 갱신되지 않습니다."
    elif name.endswith(("min_potential", "max_potential")):
        description = "연결된 장치에 전달할 전위 설정값입니다. 현재 값을 더블클릭해 음수의 mV 값으로 입력하세요. 현재 시뮬레이터에서는 이 설정값으로 출력을 자동 조절하지 않습니다."
    if description is None:
        description = "연결된 장치에 전달하는 시험용 상태 또는 측정값입니다. 현재 값을 더블클릭해 변경할 수 있습니다. 이 항목을 바꾸어도 출력 계산에는 직접 영향을 주지 않습니다."
    return f"{register['label']}\n{description}"
